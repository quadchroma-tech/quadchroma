// Zwischenablage auf der Mac-Seite des Clients.
//
// Dieselbe Schnittstelle wie clipboard.rs (Windows): watch() meldet einer
// Rolle (Herkunft), was der Benutzer hier kopiert hat (Text oder eine
// Dateiliste, siehe Inhalt), set() legt Text ab und set_dateien() eine
// Dateiliste, beide ohne die eigene Ueberwachung auszuloesen. Hier werden
// nur Pfade gelesen bzw. abgelegt, nie Dateien; die uebertraegt ein eigener
// Teil (dateien.rs). Es gibt einen Waechter; was er liest, verteilt er wie
// unter Windows an jede angemeldete Rolle mit Gegenueber
// (ablage_ruhe::Verteiler, dort auch das Entdoppeln je Rolle). Auf dem Mac
// meldet sich nur der Client an - die Host-Rolle des Macs hat ihre eigene
// Ablage (host/clipboard.m).
//
// NSPasteboard schickt keine Nachricht bei Aenderungen; es gibt nur den
// changeCount. Deshalb fragt ein Faden alle 300 ms nach. Ist die Zahl
// gestiegen, wird wie unter Windows erst gelesen, wenn sie sich
// ablage_ruhe::RUHE lang nicht mehr bewegt hat (Entprellen), und dieselbe
// Dateiliste geht innerhalb von ablage_ruhe::DOPPEL_FRIST nur einmal hinaus
// (Entdoppeln; Integrationstest, Befunde 1 und 2). Nach dem eigenen
// Schreiben merken wir uns die neue Zahl (wie OWN_SEQ in clipboard.rs),
// damit das eigene set() nicht als Kopie des Benutzers zurueckgemeldet wird.
// Waechter und set() laufen unter EINER Sperre, damit der Waechter nie
// zwischen clearContents und setString liest.
//
// Gelesen wird nach derselben Regel wie auf dem Mac-Host (host/clipboard.m):
// verdeckte Eintraege (Passwoerter) bleiben auf diesem Rechner. Tragen
// Eintraege Dateiverweise (public.file-url, Finder legt je Datei einen
// Eintrag an), wird die Dateiliste gemeldet und kein Text - auch nicht der
// Name, den Finder zusaetzlich als Text ablegt. Sonst zaehlt der Text des
// ersten Eintrags.
//
// Gelesen wird nur, solange eine angemeldete Rolle ein Gegenueber hat (der
// Client: waehrend einer Sitzung, `sitzung`). Ohne zaehlt der Waechter nur
// den changeCount mit: ab macOS 15.4 kann jedes Lesen des
// Inhalts durch ein Programm die Rueckfrage des Systems ausloesen (siehe
// host/clipboard.m), und was ohne Sitzung kopiert wurde, braucht niemand -
// es geht auch beim Sitzungsbeginn nicht nachtraeglich hinaus. Dieselbe
// Regel gilt unter Windows (clipboard.rs) fuer Client und Host-Rolle.
//
// Was vom Host kommt, traegt org.nspasteboard.TransientType und
// org.nspasteboard.AutoGeneratedType: Verwalter der Zwischenablage nehmen es
// dann nicht in ihren Verlauf auf - wie CanIncludeInClipboardHistory = 0
// unter Windows (clipboard.rs). Und es gilt nur fuer diesen Mac
// (prepareForNewContentsWithOptions mit NSPasteboardContentsCurrentHostOnly):
// die Universelle Zwischenablage traegt es nicht auf iPhone oder iPad - wie
// CanUploadToCloudClipboard = 0 unter Windows und wie beim Mac-Host
// (host/clipboard.m). Der eigene Lesefilter bleibt davon unberuehrt:
// fluechtig heisst nicht verdeckt.
//
// Alles ueber objc_msgSend von Hand, keine Kiste: objc_getClass,
// sel_registerName, objc_msgSend (mit passendem Funktionszeiger-Typ je
// Aufruf) und ein Autorelease-Pool je Durchlauf. Gelinkt wird AppKit (fuer
// NSPasteboard und die Konstanten NSPasteboardTypeString und
// NSPasteboardTypeFileURL) und libobjc.

use std::ffi::{c_char, c_void, CStr, OsString};
use std::os::unix::ffi::{OsStrExt, OsStringExt};
use std::path::PathBuf;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::{Arc, Mutex, Once};
use std::time::{Duration, Instant};

pub use crate::ablage_ruhe::Inhalt;
use crate::ablage_ruhe::{Entpreller, Verteilt, Verteiler, RUHE};
use crate::protokoll::Herkunft;

/// Obergrenze fuer einen Uebertragungsvorgang - wie auf Windows. Groesseres
/// wird stillschweigend verworfen statt abgeschnitten.
const MAX_BYTES: usize = 4 * 1024 * 1024;

/// Abstand zwischen zwei Blicken auf den changeCount.
const TAKT: Duration = Duration::from_millis(300);

/// NSUTF8StringEncoding
const NS_UTF8: usize = 4;

/// Kennzeichen aus der Verabredung unter nspasteboard.org: Passwortverwalter
/// markieren damit Inhalte, die nicht mitgeschrieben werden sollen. Ein
/// solcher Eintrag geht nicht ueber die Leitung - wie auf dem Mac-Host.
/// UNGEPRUEFT: Branchenkonvention, keine Apple-Dokumentation.
const VERDECKT: &CStr = c"org.nspasteboard.ConcealedType";

/// Kennzeichen aus derselben Verabredung: der Inhalt ist fluechtig und
/// gehoert in keinen Verlauf. Setzt set() an allem, was vom Host kommt.
/// UNGEPRUEFT wie VERDECKT: Branchenkonvention.
const FLUECHTIG: &CStr = c"org.nspasteboard.TransientType";

/// Kennzeichen aus derselben Verabredung: der Inhalt ist nicht vom Nutzer
/// kopiert, sondern von einem Programm erzeugt - wie beim Mac-Host.
/// UNGEPRUEFT wie VERDECKT: Branchenkonvention.
const AUTOGEN: &CStr = c"org.nspasteboard.AutoGeneratedType";

/// NSPasteboardContentsCurrentHostOnly (1 << 0): der Inhalt bleibt auf
/// diesem Rechner, die Universelle Zwischenablage (Handoff) nimmt ihn nicht
/// mit. UNGEPRUEFT: ob Handoff das beachtet, laesst sich nur auf Hardware
/// mit einem zweiten Apple-Geraet pruefen.
const NUR_DIESER_MAC: usize = 1;

// ------------------------------------------------------------------- FFI

type Id = *mut c_void;
type Sel = *mut c_void;

#[link(name = "objc")]
extern "C" {
    fn objc_getClass(name: *const c_char) -> Id;
    fn sel_registerName(name: *const c_char) -> Sel;
    fn objc_msgSend();
    fn objc_autoreleasePoolPush() -> *mut c_void;
    fn objc_autoreleasePoolPop(pool: *mut c_void);
}

#[link(name = "AppKit", kind = "framework")]
extern "C" {
    static NSPasteboardTypeString: Id;
    static NSPasteboardTypeFileURL: Id;
}

fn klasse(name: &CStr) -> Id {
    unsafe { objc_getClass(name.as_ptr()) }
}

fn sel(name: &CStr) -> Sel {
    unsafe { sel_registerName(name.as_ptr()) }
}

/// [obj sel] -> id
unsafe fn msg_id(obj: Id, s: Sel) -> Id {
    let f: unsafe extern "C" fn(Id, Sel) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s)
}

/// [obj sel] -> NSInteger
unsafe fn msg_int(obj: Id, s: Sel) -> isize {
    let f: unsafe extern "C" fn(Id, Sel) -> isize = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s)
}

/// [obj sel] -> BOOL
unsafe fn msg_bool(obj: Id, s: Sel) -> bool {
    let f: unsafe extern "C" fn(Id, Sel) -> u8 = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s) != 0
}

/// [obj sel:arg] -> id
unsafe fn msg_id_1(obj: Id, s: Sel, a: Id) -> Id {
    let f: unsafe extern "C" fn(Id, Sel, Id) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, a)
}

/// [obj sel:NSUInteger] -> id (objectAtIndex:)
unsafe fn msg_id_u(obj: Id, s: Sel, a: usize) -> Id {
    let f: unsafe extern "C" fn(Id, Sel, usize) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, a)
}

/// [obj sel:arg] -> BOOL (writeObjects:)
unsafe fn msg_bool_1(obj: Id, s: Sel, a: Id) -> bool {
    let f: unsafe extern "C" fn(Id, Sel, Id) -> u8 = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, a) != 0
}

/// [obj sel:arg] -> NSUInteger
unsafe fn msg_uint_1(obj: Id, s: Sel, a: usize) -> usize {
    let f: unsafe extern "C" fn(Id, Sel, usize) -> usize = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, a)
}

/// [obj sel:NSUInteger] -> NSInteger
unsafe fn msg_int_1(obj: Id, s: Sel, a: usize) -> isize {
    let f: unsafe extern "C" fn(Id, Sel, usize) -> isize = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, a)
}

/// [obj sel:a forType:b] -> BOOL
unsafe fn msg_bool_2(obj: Id, s: Sel, a: Id, b: Id) -> bool {
    let f: unsafe extern "C" fn(Id, Sel, Id, Id) -> u8 = std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, a, b) != 0
}

/// [NSString alloc] initWithBytes:length:encoding: -> id (eigene Zaehlung)
unsafe fn msg_init_bytes(obj: Id, s: Sel, bytes: *const c_void, len: usize, enc: usize) -> Id {
    let f: unsafe extern "C" fn(Id, Sel, *const c_void, usize, usize) -> Id =
        std::mem::transmute(objc_msgSend as *const c_void);
    f(obj, s, bytes, len, enc)
}

/// [NSArray arrayWithObjects:count:] -> id (autoreleased)
unsafe fn ns_liste(objekte: &[Id]) -> Id {
    let k = klasse(c"NSArray");
    if k.is_null() {
        return std::ptr::null_mut();
    }
    let f: unsafe extern "C" fn(Id, Sel, *const Id, usize) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    f(k, sel(c"arrayWithObjects:count:"), objekte.as_ptr(), objekte.len())
}

/// NSString aus einer C-Zeichenkette. Autoreleased: braucht einen Pool.
unsafe fn ns_text(s: &CStr) -> Id {
    let k = klasse(c"NSString");
    if k.is_null() {
        return std::ptr::null_mut();
    }
    msg_id_1(k, sel(c"stringWithUTF8String:"), s.as_ptr() as Id)
}

/// NSString aus UTF-8-Bytes, ohne Abschneiden an einem NUL. Eigene
/// Zaehlung: der Aufrufer gibt ihn mit release frei. Null bei ungueltigem
/// UTF-8.
unsafe fn ns_text_bytes(bytes: &[u8]) -> Id {
    let k = klasse(c"NSString");
    if k.is_null() {
        return std::ptr::null_mut();
    }
    let roh = msg_id(k, sel(c"alloc"));
    msg_init_bytes(roh, sel(c"initWithBytes:length:encoding:"), bytes.as_ptr() as *const c_void, bytes.len(), NS_UTF8)
}

/// Traegt der Eintrag diesen Typ? [item availableTypeFromArray:@[typ]]
unsafe fn hat_typ(item: Id, typ: Id) -> bool {
    let k = klasse(c"NSArray");
    if k.is_null() || typ.is_null() {
        return false;
    }
    let liste = msg_id_1(k, sel(c"arrayWithObject:"), typ);
    !liste.is_null() && !msg_id_1(item, sel(c"availableTypeFromArray:"), liste).is_null()
}

/// Ein Autorelease-Pool fuer die Dauer eines Geltungsbereichs.
struct Pool(*mut c_void);

impl Pool {
    fn neu() -> Pool {
        Pool(unsafe { objc_autoreleasePoolPush() })
    }
}

impl Drop for Pool {
    fn drop(&mut self) {
        unsafe { objc_autoreleasePoolPop(self.0) }
    }
}

// ------------------------------------------------------------ Zustand

/// changeCount nach dem eigenen Schreiben: einmal nach clearContents, einmal
/// nach setString - je nachdem, wann der Waechter hinschaut, muss einer
/// von beiden passen. Gilt fuer Text und Dateilisten.
static EIGEN: Mutex<(isize, isize)> = Mutex::new((-1, -1));

/// Serialisiert set() und set_dateien() gegen den Waechter (siehe Kopf).
static SPERRE: Mutex<()> = Mutex::new(());

/// Laeuft eine Sitzung? Nur dann liest der Waechter den Inhalt.
static SITZUNG: AtomicBool = AtomicBool::new(false);

/// Zaehlt jeden Sitzungswechsel: dieselbe Dateiliste in einer neuen Sitzung
/// ist eine neue Kopie (Entdoppler).
static SITZUNGS_WECHSEL: AtomicU64 = AtomicU64::new(0);

/// Die angemeldeten Rollen des einen Waechters.
static VERTEILER: Verteiler = Verteiler::neu();

/// Der Waechterfaden laeuft nur einmal, gleich wie viele Rollen sich anmelden.
static WAECHTER: Once = Once::new();

/// Sitzung beginnt (true, der Host hat angenommen) oder endet (false).
pub fn sitzung(an: bool) {
    if SITZUNG.swap(an, Ordering::Relaxed) != an {
        SITZUNGS_WECHSEL.fetch_add(1, Ordering::Relaxed);
    }
}

/// Das Gegenueber des Clients fuer seine Anmeldung (watch): Some(Nummer des
/// Sitzungswechsels) waehrend einer Sitzung, sonst None.
pub fn client_gegenueber() -> Option<u64> {
    SITZUNG.load(Ordering::Relaxed).then(|| SITZUNGS_WECHSEL.load(Ordering::Relaxed))
}

/// Eine Zeile des Waechters: ins Protokoll jeder Rolle, fuer die gerade
/// gelesen wird; ohne eine solche (Tests) in das des Fadens.
fn waechter_zeile(text: &str) {
    let rollen = VERTEILER.mit_gegenueber();
    if rollen.is_empty() {
        crate::protokoll::zeile(text.to_string());
    }
    for h in rollen {
        crate::protokoll::zeile_als(h, text.to_string());
    }
}

/// Das allgemeine Brett. Null, wenn AppKit nicht da ist - dann tut alles
/// hier still nichts.
fn brett() -> Id {
    let k = klasse(c"NSPasteboard");
    if k.is_null() {
        return std::ptr::null_mut();
    }
    unsafe { msg_id(k, sel(c"generalPasteboard")) }
}

fn change_count(b: Id) -> isize {
    unsafe { msg_int(b, sel(c"changeCount")) }
}

