/// Was auf dem Brett liegt: eine Dateiliste, wenn Eintraege Dateiverweise
/// (public.file-url) tragen, sonst der Text des ERSTEN Eintrags. Bewusst
/// ueber pasteboardItems und nicht ueber [b stringForType:]: der bequeme Weg
/// auf Brettebene haengt bei mehreren Eintraegen deren Text aneinander.
///
/// Betrachtet werden alle Eintraege: Finder legt je Datei einen an, und ein
/// verdeckter Eintrag irgendwo haelt alles zurueck. None, wenn etwas
/// verdeckt ist, ein Dateiverweis sich nicht aufloesen laesst (lieber keine
/// Liste als eine halbe), nichts Textartiges anliegt oder der Text die
/// Obergrenze reisst. Laeuft im eigenen Pool: die Rueckgaben sind
/// autoreleased.
fn lesen(b: Id) -> Option<Inhalt> {
    let _pool = Pool::neu();
    unsafe {
        let eintraege = msg_id(b, sel(c"pasteboardItems"));
        if eintraege.is_null() {
            return None;
        }
        let anzahl = msg_int(eintraege, sel(c"count"));
        if anzahl <= 0 {
            return None;
        }
        // Verdeckte Inhalte (Passwoerter) bleiben auf diesem Rechner. Laesst
        // sich das Kennzeichen nicht einmal anlegen, wird nichts gelesen -
        // im Zweifel lieber keine Kopie als ein Passwort auf dem Host.
        let verdeckt = ns_text(VERDECKT);
        if verdeckt.is_null() {
            return None;
        }
        let mut pfade = Vec::new();
        let mut dateiverweise = 0usize;
        let mut unaufloesbar = false;
        for i in 0..anzahl as usize {
            let item = msg_id_u(eintraege, sel(c"objectAtIndex:"), i);
            if item.is_null() {
                continue;
            }
            if hat_typ(item, verdeckt) {
                waechter_zeile("Zwischenablage: Eintrag ist als verdeckt markiert, nicht uebertragen");
                return None;
            }
            if hat_typ(item, NSPasteboardTypeFileURL) {
                dateiverweise += 1;
                // Mehr Dateiverweise liest der Waechter nicht: mehr als
                // EINTRAEGE_MAX (Spezifikation 2.6) koennen ohnehin nicht
                // hinaus, einer darueber reicht dem Sender fuer "zu viele".
                if pfade.len() <= crate::dateien::EINTRAEGE_MAX as usize {
                    match dateiverweis(item) {
                        Some(p) => pfade.push(p),
                        None => unaufloesbar = true,
                    }
                }
            }
        }
        if dateiverweise > 0 {
            if unaufloesbar {
                waechter_zeile("Zwischenablage: Dateiverweis nicht aufloesbar, nichts uebertragen");
                return None;
            }
            return Some(Inhalt::Dateien(pfade));
        }

        if anzahl > 1 {
            waechter_zeile(&format!("Zwischenablage: {anzahl} Eintraege, nur der erste wird uebertragen"));
        }
        let item = msg_id(eintraege, sel(c"firstObject"));
        if item.is_null() {
            return None;
        }
        let s = msg_id_1(item, sel(c"stringForType:"), NSPasteboardTypeString);
        if s.is_null() {
            return None;
        }
        let len = msg_uint_1(s, sel(c"lengthOfBytesUsingEncoding:"), NS_UTF8);
        if len == 0 || len > MAX_BYTES {
            return None;
        }
        let p = msg_id(s, sel(c"UTF8String")) as *const u8;
        if p.is_null() {
            return None;
        }
        let bytes = std::slice::from_raw_parts(p, len);
        Some(Inhalt::Text(String::from_utf8_lossy(bytes).into_owned()))
    }
}

/// Text vom Brett zum Einfuegen in ein eigenes Feld (Adresse und Passwort,
/// Cmd+V). Anders als der Waechter liest es auch ohne Sitzung und auch
/// verdeckte Eintraege (etwa das Passwort, das der Mac-Host kopiert): der
/// Nutzer fuegt selbst ein, und der Text bleibt in diesem Programm - er
/// geht nicht zum Host. None: kein Text, zu gross oder kein AppKit.
pub fn text_einfuegen() -> Option<String> {
    let _pool = Pool::neu();
    let b = brett();
    if b.is_null() {
        return None;
    }
    unsafe {
        let s = msg_id_1(b, sel(c"stringForType:"), NSPasteboardTypeString);
        if s.is_null() {
            return None;
        }
        let len = msg_uint_1(s, sel(c"lengthOfBytesUsingEncoding:"), NS_UTF8);
        if len == 0 || len > MAX_BYTES {
            return None;
        }
        let p = msg_id(s, sel(c"UTF8String")) as *const u8;
        if p.is_null() {
            return None;
        }
        Some(String::from_utf8_lossy(std::slice::from_raw_parts(p, len)).into_owned())
    }
}

/// Der Pfad hinter dem Dateiverweis (public.file-url) eines Eintrags, ueber
/// datei_url. Der Pfad kommt aus `path`, also in der Schreibweise des
/// Verweises. Die kann Umlaute zerlegt (NFD) tragen - fileURLWithPath: legt
/// sie so an -, auch wenn der Name auf der Platte zusammengesetzt steht; auf
/// APFS meinen beide Schreibweisen dieselbe Datei. Nur innerhalb eines Pools
/// aufrufen.
unsafe fn dateiverweis(item: Id) -> Option<PathBuf> {
    let s = msg_id_1(item, sel(c"stringForType:"), NSPasteboardTypeFileURL);
    let url = datei_url(s)?;
    let pfad = msg_id(url, sel(c"path"));
    if pfad.is_null() {
        return None;
    }
    let p = msg_id(pfad, sel(c"UTF8String")) as *const c_char;
    if p.is_null() {
        return None;
    }
    let bytes = CStr::from_ptr(p).to_bytes();
    if !bytes.starts_with(b"/") {
        return None;
    }
    Some(PathBuf::from(OsString::from_vec(bytes.to_vec())))
}

/// Aus dem Text eines Dateiverweises ein Pfad-URL. Finder legt oft
/// Datei-Referenz-URLs ab (file:///.file/id=...); die werden ueber
/// filePathURL aufgeloest - das braucht die Datei, ein geloeschter Verweis
/// ergibt also None. Gewoehnliche Pfad-URLs werden nur umgeformt, ohne das
/// Dateisystem zu fragen. None auch, wenn es kein Datei-URL ist. Nur
/// innerhalb eines Pools aufrufen (autoreleased).
unsafe fn datei_url(text: Id) -> Option<Id> {
    let url_klasse = klasse(c"NSURL");
    if text.is_null() || url_klasse.is_null() {
        return None;
    }
    let mut url = msg_id_1(url_klasse, sel(c"URLWithString:"), text);
    if url.is_null() {
        return None;
    }
    if msg_bool(url, sel(c"isFileReferenceURL")) {
        url = msg_id(url, sel(c"filePathURL"));
        if url.is_null() {
            return None;
        }
    }
    if !msg_bool(url, sel(c"isFileURL")) {
        return None;
    }
    Some(url)
}

// ----------------------------------------------------------------- Schreiben

/// Schreibt Text auf das Brett, ohne die eigene Ueberwachung auszuloesen.
/// Scheitert still: ein verlorener Kopiervorgang ist hinnehmbar, ein Absturz
/// des Clients waehrend einer laufenden Sitzung nicht.
pub fn set(text: &str) {
    if text.len() > MAX_BYTES {
        return;
    }
    let _sperre = SPERRE.lock().unwrap_or_else(|e| e.into_inner());
    let b = brett();
    if b.is_null() {
        return;
    }
    if let Some(zaehler) = ablegen(b, text) {
        if let Ok(mut e) = EIGEN.lock() {
            *e = zaehler;
        }
    }
}

/// Legt `text` als einzigen Eintrag auf `b`: nur fuer diesen Mac, als
/// fluechtig und programmerzeugt gekennzeichnet (FLUECHTIG, AUTOGEN). Gibt
/// den changeCount nach dem Leeren und nach dem letzten Schreiben zurueck -
/// beide muss der Waechter als eigenen Vorgang erkennen.
fn ablegen(b: Id, text: &str) -> Option<(isize, isize)> {
    let _pool = Pool::neu();
    unsafe {
        // initWithBytes statt stringWithUTF8String: kein Abschneiden an
        // einem NUL im Text, und die Laenge steht fest.
        let s = ns_text_bytes(text.as_bytes());
        if s.is_null() {
            return None;
        }
        // Leeren wie clearContents, dazu "nur dieser Mac"; die Rueckgabe ist
        // wie dort der neue changeCount.
        let nach_leeren = msg_int_1(b, sel(c"prepareForNewContentsWithOptions:"), NUR_DIESER_MAC);
        let ok = msg_bool_2(b, sel(c"setString:forType:"), s, NSPasteboardTypeString);
        let _ = msg_id(s, sel(c"release"));
        // Die Kennzeichen an denselben (ersten) Eintrag, mit leerem Wert -
        // gezaehlt wird der Stand danach, damit auch dieser Schritt als
        // eigener Vorgang gilt.
        let leer = ns_text(c"");
        for kennzeichen in [FLUECHTIG, AUTOGEN] {
            let typ = ns_text(kennzeichen);
            if ok && !typ.is_null() && !leer.is_null() {
                let _ = msg_bool_2(b, sel(c"setString:forType:"), leer, typ);
            }
        }
        let nach_setzen = if ok { change_count(b) } else { nach_leeren };
        Some((nach_leeren, nach_setzen))
    }
}

/// Legt eine Dateiliste auf das allgemeine Brett, so dass "Einsetzen" im
/// Finder die Dateien kopiert - ohne die eigene Ueberwachung auszuloesen
/// (Zaehlung wie bei set()). Je Pfad ein Eintrag mit public.file-url, als
/// fluechtig und programmerzeugt gekennzeichnet, nur fuer diesen Mac.
/// `pfade` sind vollstaendige Pfade der obersten Eintraege; die Dateien
/// selbst werden hier nicht gelesen. true, wenn die Liste auf dem Brett
/// liegt; false bei leerer oder ungueltiger Liste (dann bleibt das Brett,
/// wie es ist) oder wenn das Schreiben scheitert. Aufrufer ist der
/// Empfaenger der Dateiuebertragung (dateien.rs) in seinem Schreibfaden;
/// `h` ist seine Rolle: in ihr Protokoll geht die Zeile, wenn das Schreiben
/// scheitert (wie unter Windows).
pub fn set_dateien(h: Herkunft, pfade: &[PathBuf]) -> bool {
    let _sperre = SPERRE.lock().unwrap_or_else(|e| e.into_inner());
    let b = brett();
    if b.is_null() {
        return false;
    }
    dateien_setzen(h, b, pfade)
}

/// set_dateien auf dem Brett `b`, mit der Zaehlung fuer den Widerhall.
fn dateien_setzen(h: Herkunft, b: Id, pfade: &[PathBuf]) -> bool {
    match dateien_ablegen(b, pfade) {
        Some((zaehler, ok)) => {
            if let Ok(mut e) = EIGEN.lock() {
                *e = zaehler;
            }
            if !ok {
                crate::protokoll::zeile_als(h, "Zwischenablage: Dateiliste nicht abgelegt (writeObjects: gescheitert)".into());
            }
            ok
        }
        None => false,
    }
}

/// Legt je Pfad einen NSPasteboardItem mit public.file-url (absoluteString
/// von fileURLWithPath:) und den Kennzeichen FLUECHTIG und AUTOGEN auf `b`,
/// vorher prepareForNewContentsWithOptions: "nur dieser Mac". Gibt die
/// Zaehler wie `ablegen` zurueck und ob writeObjects: gelang. None, wenn
/// schon das Bauen der Eintraege scheitert (leere Liste, relativer Pfad,
/// NUL, kein UTF-8) - dann ist das Brett unberuehrt.
fn dateien_ablegen(b: Id, pfade: &[PathBuf]) -> Option<((isize, isize), bool)> {
    if pfade.is_empty() {
        return None;
    }
    let _pool = Pool::neu();
    unsafe {
        let mut items: Vec<Id> = Vec::with_capacity(pfade.len());
        for p in pfade {
            match datei_eintrag(p) {
                Some(item) => items.push(item),
                None => {
                    for i in items {
                        let _ = msg_id(i, sel(c"release"));
                    }
                    return None;
                }
            }
        }
        let liste = ns_liste(&items);
        let geschrieben = if liste.is_null() {
            None
        } else {
            let nach_leeren = msg_int_1(b, sel(c"prepareForNewContentsWithOptions:"), NUR_DIESER_MAC);
            let ok = msg_bool_1(b, sel(c"writeObjects:"), liste);
            let nach_setzen = if ok { change_count(b) } else { nach_leeren };
            Some(((nach_leeren, nach_setzen), ok))
        };
        for i in items {
            let _ = msg_id(i, sel(c"release"));
        }
        geschrieben
    }
}

/// Ein Eintrag fuer `pfad`: public.file-url plus FLUECHTIG und AUTOGEN.
/// Eigene Zaehlung (alloc/init), der Aufrufer gibt ihn frei. Nur innerhalb
/// eines Pools aufrufen.
unsafe fn datei_eintrag(pfad: &PathBuf) -> Option<Id> {
    let bytes = pfad.as_os_str().as_bytes();
    if !pfad.is_absolute() || bytes.contains(&0) {
        return None;
    }
    let url_klasse = klasse(c"NSURL");
    let item_klasse = klasse(c"NSPasteboardItem");
    let leer = ns_text(c"");
    let fluechtig = ns_text(FLUECHTIG);
    let autogen = ns_text(AUTOGEN);
    if url_klasse.is_null() || item_klasse.is_null() || leer.is_null() || fluechtig.is_null() || autogen.is_null() {
        return None;
    }
    let s = ns_text_bytes(bytes);
    if s.is_null() {
        return None;
    }
    // fileURLWithPath: fragt das Dateisystem, ob es ein Ordner ist, und
    // haengt dann den Schraegstrich an - so erkennt Finder Ordner.
    let url = msg_id_1(url_klasse, sel(c"fileURLWithPath:"), s);
    let _ = msg_id(s, sel(c"release"));
    if url.is_null() {
        return None;
    }
    let text = msg_id(url, sel(c"absoluteString"));
    if text.is_null() {
        return None;
    }
    let item = msg_id(msg_id(item_klasse, sel(c"alloc")), sel(c"init"));
    if item.is_null() {
        return None;
    }
    let setzen = sel(c"setString:forType:");
    if !msg_bool_2(item, setzen, text, NSPasteboardTypeFileURL)
        || !msg_bool_2(item, setzen, leer, fluechtig)
        || !msg_bool_2(item, setzen, leer, autogen)
    {
        let _ = msg_id(item, sel(c"release"));
        return None;
    }
    Some(item)
}

/// Stammt dieser changeCount von unserem eigenen set()?
fn eigener_vorgang(count: isize) -> bool {
    EIGEN
        .lock()
        .map(|e| count == e.0 || count == e.1)
        .unwrap_or(false)
}

// -------------------------------------------------------------- Ueberwachung

/// Ein Blick des Waechters auf `b`: hat sich der changeCount seit `zuletzt`
/// bewegt, und stammt die Aenderung nicht von uns, wird gelesen - aber nur
/// mit laufender Sitzung. Ohne sie wird nur mitgezaehlt; eine Aenderung von
/// vorher holt auch der Sitzungsbeginn nicht nach.
fn nachsehen(b: Id, zuletzt: &mut isize, sitzung: bool, lesen: impl FnOnce(Id) -> Option<Inhalt>) -> Option<Inhalt> {
    let jetzt = change_count(b);
    if jetzt == *zuletzt {
        return None;
    }
    *zuletzt = jetzt;
    if eigener_vorgang(jetzt) || !sitzung {
        return None; // unser eigener Schreibvorgang, oder niemand zum Senden
    }
    lesen(b)
}

/// Was der Waechter zwischen zwei Blicken weiss.
struct Wache {
    /// changeCount beim letzten Blick - bewegt er sich, beginnt die Ruhe neu.
    gesehen: isize,
    /// changeCount, ueber den nachsehen() zuletzt entschieden hat.
    zuletzt: isize,
    ruhe: Entpreller,
}

impl Wache {
    fn neu(b: Id) -> Wache {
        let c = change_count(b);
        Wache { gesehen: c, zuletzt: c, ruhe: Entpreller::neu(RUHE) }
    }

    /// Ein Blick auf `b` zur Zeit `jetzt`: hat sich der changeCount bewegt,
    /// beginnt die Ruhe (neu); ist sie um, wird einmal nachgesehen (nachsehen:
    /// nur mit Gegenueber - `sitzung`: irgendeine Rolle hat eines -, nie der
    /// eigene Vorgang). Eine Aenderung ohne Gegenueber wird nur mitgezaehlt -
    /// auch dann, wenn die Sitzung waehrend der Ruhe beginnt. Entdoppelt wird
    /// danach beim Verteilen, je Rolle. Unter SPERRE aufrufen.
    fn blick(&mut self, b: Id, jetzt: Instant, sitzung: bool, lesen: impl FnOnce(Id) -> Option<Inhalt>) -> Option<Inhalt> {
        let c = change_count(b);
        if c != self.gesehen {
            self.gesehen = c;
            if sitzung {
                self.ruhe.aenderung(jetzt);
            } else {
                self.zuletzt = c;
                self.ruhe.verwerfen();
            }
            return None;
        }
        if !self.ruhe.faellig(jetzt) {
            return None;
        }
        nachsehen(b, &mut self.zuletzt, sitzung, lesen).filter(|i| !i.leer())
    }
}

/// Was der Waechter las, an die Rollen (ablage_ruhe::Verteiler); eine
/// Dateiliste, die eine Rolle gerade eben schon bekam, steht nur in ihrem
/// Protokoll.
fn verteilen(v: &Verteiler, inhalt: &Inhalt, jetzt: Instant) {
    for (h, verteilt) in v.verteilen(inhalt, jetzt) {
        if verteilt == Verteilt::Doppelt {
            crate::protokoll::zeile_als(h, "Zwischenablage: dieselbe Dateiliste noch einmal gemeldet - uebergangen".into());
        }
    }
}

/// Meldet die Rolle `h` beim Waechter an und startet ihn beim ersten Mal in
/// einem eigenen Faden (einer fuer alle Rollen; eine zweite Anmeldung
/// derselben Rolle ersetzt die erste). `gegenueber` sagt, ob die Rolle
/// gerade ein Gegenueber hat und in welcher Sitzung (der Client nimmt
/// client_gegenueber). `cb` bekommt jeden Text und jede Dateiliste, die der
/// Benutzer auf dem Mac kopiert, solange diese Rolle ein Gegenueber hat;
/// eigene Schreibvorgaenge aus `set` und `set_dateien` sind bereits
/// herausgefiltert. Was beim Start oder ohne Gegenueber auf das Brett kam,
/// wird nicht gemeldet - wie auf Windows, wo erst die naechste Aenderung in
/// einer Sitzung zaehlt. Gemeldet wird erst, wenn das Brett RUHE lang ruhig
/// war (Wache::blick), und dieselbe Dateiliste je Rolle nur einmal
/// (ablage_ruhe::Verteiler). Beide Rueckrufe laufen ausserhalb der Sperre im
/// Faden des Waechters.
pub fn watch(
    h: Herkunft,
    gegenueber: impl Fn() -> Option<u64> + Send + Sync + 'static,
    cb: impl Fn(Inhalt) + Send + Sync + 'static,
) {
    VERTEILER.anmelden(h, Arc::new(gegenueber), Arc::new(cb));
    WAECHTER.call_once(|| {
        std::thread::spawn(|| {
            let b = brett();
            if b.is_null() {
                eprintln!("Zwischenablage: Ueberwachung nicht gestartet: NSPasteboard fehlt");
                return;
            }
            let mut wache = Wache::neu(b);
            loop {
                // Im Takt - aber nicht laenger als bis zum Ende der Ruhe.
                std::thread::sleep(wache.ruhe.schlaf(Instant::now(), TAKT));
                // Wer ein Gegenueber hat, fragt der Verteiler vor der Sperre -
                // die Rueckrufe der Rollen laufen nie unter ihr.
                let da = VERTEILER.jemand_da();
                let inhalt = {
                    let _sperre = SPERRE.lock().unwrap_or_else(|e| e.into_inner());
                    wache.blick(b, Instant::now(), da, lesen)
                };
                if let Some(i) = inhalt {
                    verteilen(&VERTEILER, &i, Instant::now());
                }
            }
        });
    });
}

